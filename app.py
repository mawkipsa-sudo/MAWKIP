def select_social_actions(user_message, session_id):
    intent = detect_social_intent(user_message)
    customer = get_customer(session_id) or {}
    try:
        shown_history = json.loads(customer.get('shown_actions') or '[]')
        if not isinstance(shown_history, list):
            shown_history = []
    except (TypeError, json.JSONDecodeError):
        shown_history = []
    channel_keys = [
        key for key in intent['channels']
        if enabled_channel(key)
    ]

    if channel_keys and not intent['explicit']:
        previously_shown = set(shown_history)
        fresh_channels = [key for key in channel_keys if key not in previously_shown]
        if fresh_channels:
            channel_keys = fresh_channels

    actions = []
    for channel_key in channel_keys:
        action = build_social_action(channel_key, customer)
        if action:
            actions.append(action)

    shown_actions = list(dict.fromkeys([
        *shown_history,
        *(action['id'] for action in actions),
    ]))[-12:]
    update_customer(
        session_id,
        customer_intent=intent['intent'],
        shown_actions=json.dumps(shown_actions, ensure_ascii=False),
    )
    return intent, actions


