@app.route('/api/chat', methods=['POST'])
def chat():
    data = request.get_json(silent=True) or {}
    user_message = str(data.get('message', '')).strip()
    session_id = normalize_session_id(data.get('session_id'))
    if not user_message:
        return jsonify({'error': 'Message is required', 'session_id': session_id}), 400
    if len(user_message) > 1200:
        return jsonify({'error': 'Message is too long', 'session_id': session_id}), 400

    ensure_customer(session_id)
    stored_history = get_history(session_id, limit=12)
    conversation = [
        {'role': item['role'], 'content': item['message']}
        for item in stored_history
    ]
    conversation.append({'role': 'user', 'content': user_message})
    save_message(session_id, 'user', user_message)

    customer_data = extract_customer_data(user_message)
    update_customer(session_id, **customer_data)
    social_intent, actions = select_social_actions(user_message, session_id)
    action_context = {
        'intent': social_intent['intent'],
        'stage': social_intent['stage'],
    }

    if social_intent['intent'] == 'youtube_request':
        reply = 'قناة يوتيوب غير متاحة حاليًا. تقدر تشوف فيديوهات موكب عبر تيك توك، أو تطلب مني رابط منصة أخرى.'
        save_message(session_id, 'assistant', reply)
        return jsonify({
            'reply': reply,
            'suggestions': ['أرسل لي تيك توك', 'أرسل لي إنستغرام', 'أعرض كل حساباتكم'],
            'actions': [],
            'action_context': action_context,
            'session_id': session_id,
            'model': 'deterministic-routing',
        })

    routing_reply = social_routing_reply(social_intent['intent'])
    if routing_reply and actions:
        save_message(session_id, 'assistant', routing_reply)
        return jsonify({
            'reply': routing_reply,
            'suggestions': [],
            'actions': actions,
            'action_context': action_context,
            'session_id': session_id,
            'model': 'deterministic-routing',
        })

    if client is None:
        reply, suggestions = build_local_consultation_reply(user_message, session_id)
        save_message(session_id, 'assistant', reply)
        return jsonify({
            'reply': reply,
            'suggestions': suggestions,
            'actions': actions,
            'action_context': action_context,
            'session_id': session_id,
            'model': 'mawkib-local-consultant',
            'degraded': True,
        })

    try:
        # Persist newly discovered facts before generating the answer so the
        # model receives one consistent customer profile on every turn.
        system_prompt = build_contextual_system_prompt(conversation)
        customer_memory = build_customer_memory(session_id, conversation)
        messages = [{'role': 'system', 'content': system_prompt}]
        if customer_memory:
            messages.append({'role': 'system', 'content': customer_memory})
        messages.extend([
            {'role': 'system', 'content': SUGGESTION_OUTPUT_INSTRUCTION},
            *conversation,
        ])
        response = create_groq_completion(
            messages,
            max_tokens=2600,
            timeout=120.0,
        )
        reply, suggestions = parse_assistant_output(
            response.choices[0].message.content,
            user_message,
        )
        reply, suggestions = enforce_mawkib_output(
            reply,
            suggestions,
            user_message,
        )
        if not reply:
            raise RuntimeError('Groq returned an empty response.')
        save_message(session_id, 'assistant', reply)
        return jsonify({
            'reply': reply,
            'suggestions': suggestions,
            'actions': actions,
            'action_context': action_context,
            'session_id': session_id,
            'model': ACTIVE_GROQ_MODEL,
            'degraded': False,
        })
    except Exception as e:
        error_message = clean_error_message(e)
        print('Groq chat error')
        print(error_message)
        traceback.print_exc()
        fallback_reply, fallback_options = build_local_consultation_reply(user_message, session_id)
        save_message(session_id, 'assistant', fallback_reply)
        return jsonify({
            'reply': fallback_reply,
            'suggestions': fallback_options,
            'actions': actions or [
                action for action in (
                    build_social_action('whatsapp', get_customer(session_id) or {}),
                    build_social_action('phone', get_customer(session_id) or {}),
                )
                if action
            ],
            'action_context': action_context,
            'session_id': session_id,
            'model': 'mawkib-local-consultant',
            'degraded': True,
        })

