def build_training_chunks(training_text):
    headings = list(re.finditer(r'(?m)^#\s+(?=\d+\.\s|النتيجة النهائية|OFFICIAL)', training_text))
    chunks = []
    for index, match in enumerate(headings):
        end = headings[index + 1].start() if index + 1 < len(headings) else len(training_text)
        chunk = training_text[match.start():end].strip()
        if not chunk:
            continue
        heading = chunk.splitlines()[0].lstrip('#').strip()
        chunks.append({
            'heading': heading,
            'content': chunk,
            'heading_tokens': training_tokens(heading),
            'content_tokens': training_tokens(chunk),
        })
    return chunks


def training_tokens(text):
    normalized = text.lower().translate(str.maketrans('أإآةى', 'اااهي'))
    return {
        token
        for token in re.findall(r'[\w\u0600-\u06ff]{3,}', normalized)
        if token not in TRAINING_STOP_WORDS_NORMALIZED
    }


TRAINING_CHUNKS = build_training_chunks(SYSTEM_PROMPT)


def select_training_context(query, limit=5, max_chars=9000):
    query_text = str(query or '').strip()
    if not query_text:
        return ''

    query_tokens = training_tokens(query_text)
    normalized_query = query_text.lower()
    ranked = []

    for index, chunk in enumerate(TRAINING_CHUNKS):
        heading = chunk['heading']
        content = chunk['content']
        heading_tokens = chunk['heading_tokens']
        content_tokens = chunk['content_tokens']
        score = (len(query_tokens & heading_tokens) * 6) + len(query_tokens & content_tokens)
        if normalize_arabic_text(heading) in normalize_arabic_text(query_text):
            score += 24

        for triggers, heading_hints in TRAINING_TOPIC_HINTS:
            if any(trigger.lower() in normalized_query for trigger in triggers):
                if any(hint.lower() in heading.lower() for hint in heading_hints):
                    score += 18

        if score > 0:
            ranked.append((score, -index, content))

    selected = []
    current_length = 0
    for _, _, content in sorted(ranked, reverse=True):
        if len(selected) >= limit:
            break
        remaining = max_chars - current_length
        if remaining < 300:
            break
        if len(content) > remaining and selected:
            continue
        selected_content = content[:remaining]
        selected.append(selected_content)
        current_length += len(selected_content)

    return '\n\n'.join(selected)


def build_contextual_system_prompt(conversation):
    recent_customer_messages = [
        item.get('content', '')
        for item in conversation[-8:]
        if item.get('role') == 'user'
    ]
    latest_customer_message = recent_customer_messages[-1] if recent_customer_messages else ''
    weighted_query = ' '.join([
        *recent_customer_messages,
        latest_customer_message,
        latest_customer_message,
    ])
    training_context = select_training_context(weighted_query)
    if not training_context:
        return GROQ_SYSTEM_PROMPT

    return (
        f'{GROQ_SYSTEM_PROMPT}\n\n'
        'تدريب موكب السياقي التالي مستخرج من الدليل الرئيسي. طبّق ما يلائم سؤال العميل فقط، '
        'ولا تذكر الدليل أو عملية الاسترجاع في ردك:\n\n'
        f'{training_context}'
    )


def build_customer_memory(session_id, conversation):
    """Build a small, explicit memory block from facts the customer provided."""
    customer = get_customer(session_id) or {}
    user_text = ' '.join(
        item.get('content', '')
        for item in conversation
        if item.get('role') == 'user'
    )

    # Extract from the complete customer side of the conversation so a fact
    # mentioned several turns ago is available before the next model call.
    observed = extract_customer_data(user_text)
    merged = {
        key: value
        for key, value in {**customer, **observed}.items()
        if value not in (None, '', 0, False)
    }
    labels = {
        'event_type': 'المناسبة',
        'city': 'المدينة',
        'guest_count': 'عدد الضيوف',
        'venue': 'مكان المناسبة',
        'event_date': 'تاريخ المناسبة',
        'style_preference': 'الذوق أو الأسلوب',
        'budget_level': 'مستوى الميزانية',
    }
    facts = [f'{labels[key]}: {merged[key]}' for key in labels if key in merged]
    if not facts:
        return ''
    return (
        'ذاكرة العميل من المعلومات التي ذكرها بنفسه (استخدمها ولا تسأل عنها مجددًا):\n'
        + '\n'.join(f'- {fact}' for fact in facts)
        + '\nإذا كانت معلومة ناقصة، اسأل عن الأهم فقط ولا تعرض هذه الذاكرة كحقول داخلية.'
    )

