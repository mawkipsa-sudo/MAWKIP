def parse_assistant_output(content, user_message):
    raw_content = str(content or '').strip()
    start_token = '<<<MAWKIB_OPTIONS>>>'
    end_token = '<<<END_OPTIONS>>>'
    suggestions = []

    try:
        structured = json.loads(raw_content)
    except (TypeError, json.JSONDecodeError):
        structured = None

    if isinstance(structured, dict):
        reply = str(structured.get('reply') or '').strip()
        raw_suggestions = structured.get('suggestions')
        if isinstance(raw_suggestions, list):
            for item in raw_suggestions:
                suggestion = re.sub(r'\s+', ' ', str(item or '')).strip()
                if not suggestion or len(suggestion) > 80:
                    continue
                if '?' in suggestion or '؟' in suggestion:
                    continue
                if suggestion not in suggestions:
                    suggestions.append(suggestion)
    elif start_token in raw_content:
        before_options, options_tail = raw_content.split(start_token, 1)
        options_block, separator, after_options = options_tail.partition(end_token)
        reply = f'{before_options}\n{after_options if separator else ""}'.strip()
        for line in options_block.splitlines():
            suggestion = re.sub(r'^\s*(?:[-•*]|\d+[.)-]?)\s*', '', line).strip(' "\'\t\r\n')
            suggestion = re.sub(r'\s+', ' ', suggestion)
            if '?' in suggestion or '؟' in suggestion:
                continue
            if 'واتساب' in suggestion and 'واتساب' not in f'{user_message} {reply}':
                continue
            if suggestion and len(suggestion) <= 80 and suggestion not in suggestions:
                suggestions.append(suggestion)
    else:
        reply = raw_content

    reply = re.sub(r'https?://\S+', '', reply.replace(end_token, '')).strip()
    reply = re.sub(r'[*_~`#]+', '', reply)
    reply = re.sub(
        '[\U0001F1E6-\U0001F1FF\U0001F300-\U0001FAFF\u2600-\u27BF\uFE0F\u20E3]',
        '',
        reply,
    )
    reply = re.sub(r'(?m)^\s*[1-3]\s*[.)-]?\s+', '', reply)
    reply = re.sub(r'\n{3,}', '\n\n', reply)
    reply = re.sub(r'[ \t]{2,}', ' ', reply)
    if len(suggestions) < 3:
        for fallback in fallback_suggestions(user_message, reply):
            if fallback not in suggestions:
                suggestions.append(fallback)
            if len(suggestions) == 3:
                break
    return reply, suggestions[:3]


def enforce_mawkib_output(reply, suggestions, user_message):
    """Final deterministic guard for brand accuracy and unsupported assumptions."""
    cleaned_reply = str(reply or '').strip()
    normalized_user = normalize_arabic_text(user_message)
