def is_unavailable_model_error(error):
    message = str(error).lower()
    return any(
        marker in message
        for marker in ('model_decommissioned', 'model_not_found', 'does not exist', 'not found', 'not permitted')
    )


def is_transient_model_error(error):
    message = str(error).lower()
    return any(
        marker in message
        for marker in (
            'rate limit', '429', 'timeout', 'timed out', 'connection',
            '502', '503', '504', 'temporarily unavailable', 'overloaded',
        )
    )


def is_structured_output_error(error):
    message = str(error).lower()
    return any(
        marker in message
        for marker in ('json_validate_failed', 'failed to validate json', 'failed_generation')
    )


def build_completion_options(model_name, messages, max_tokens, timeout):
    options = {
        'model': model_name,
        'messages': messages,
        'temperature': GROQ_TEMPERATURE,
        'top_p': GROQ_TOP_P,
        'max_completion_tokens': max_tokens,
        'timeout': timeout,
    }
    if model_name.startswith('openai/gpt-oss-'):
        options['reasoning_effort'] = (
            GROQ_REASONING_EFFORT
            if GROQ_REASONING_EFFORT in {'low', 'medium', 'high'}
            else 'high'
        )
        options['extra_body'] = {'reasoning_format': 'hidden'}
        options['response_format'] = ASSISTANT_RESPONSE_FORMAT
    elif model_name.startswith('qwen/'):
        options['reasoning_effort'] = 'default'
        options['extra_body'] = {'reasoning_format': 'hidden'}
        options['response_format'] = {'type': 'json_object'}
    else:
        options['response_format'] = {'type': 'json_object'}
    return options


def create_groq_completion(messages, max_tokens=500, timeout=120.0):
    global ACTIVE_GROQ_MODEL

    if client is None:
        raise RuntimeError('GROQ_API_KEY is not configured.')

    models_to_try = list(dict.fromkeys([ACTIVE_GROQ_MODEL, GROQ_FALLBACK_MODEL]))

    last_error = None
    for model_name in models_to_try:
        options = build_completion_options(model_name, messages, max_tokens, timeout)
        for attempt in range(GROQ_MAX_RETRIES + 1):
            try:
                response = client.chat.completions.create(**options)
                ACTIVE_GROQ_MODEL = model_name
                return response
            except Exception as error:
                last_error = error
                transient = is_transient_model_error(error)
                if is_structured_output_error(error) and attempt < GROQ_MAX_RETRIES:
                    options = {**options}
                    if attempt == 0:
                        options['response_format'] = {'type': 'json_object'}
                    else:
                        options.pop('response_format', None)
                        if model_name.startswith('openai/gpt-oss-'):
                            options['reasoning_effort'] = 'medium'
                    time.sleep(0.2 * (2 ** attempt))
                    continue
                if transient and attempt < GROQ_MAX_RETRIES:
                    time.sleep(0.35 * (2 ** attempt))
                    continue
                break

        if (
            is_unavailable_model_error(last_error)
            or is_transient_model_error(last_error)
            or is_structured_output_error(last_error)
        ):
            ACTIVE_GROQ_MODEL = GROQ_FALLBACK_MODEL
            print(f'Groq model {model_name} failed; trying {GROQ_FALLBACK_MODEL}')
            continue
        raise last_error

    raise last_error or RuntimeError('No Groq model is available.')


def extract_customer_data(user_message, assistant_reply=''):
    user_text = user_message.lower().strip()
    assistant_text = assistant_reply.lower().strip()
    combined_text = f'{user_text} {assistant_text}'
    extracted = {}

    event_patterns = [
        ('زفاف', ['زفاف', 'زواج', 'عرس']),
        ('ملكة أو خطوبة', ['ملكة', 'ملكه', 'خطوبة', 'خطوبه']),
        ('تخرج', ['تخرج']),
        ('استقبال مولود', ['مولود', 'مواليد', 'بيبي']),
        ('عيد ميلاد', ['عيد ميلاد', 'ميلاد']),
        ('افتتاح', ['افتتاح']),
        ('مناسبة خاصة', ['مناسبة خاصة', 'مناسبه خاصه']),
    ]
    for event_type, keywords in event_patterns:
        if any(keyword in combined_text for keyword in keywords):
            extracted['event_type'] = event_type
            break

    budget_patterns = [
        ('مدروس وأنيق', ['مدروس', 'اقتصادي', 'محدود', 'محدوده', 'بسيط']),
        ('متوسط', ['متوسط']),
        ('فاخر', ['فاخر', 'مفتوحة', 'مفتوحه', 'بدون حد']),
        ('حسب التصميم', ['حسب التصميم']),
    ]
    for budget_level, keywords in budget_patterns:
        if any(keyword in user_text for keyword in keywords):
            extracted['budget_level'] = budget_level
            break

    style_terms = [
        'quiet luxury', 'عاجي', 'شامبين', 'موكا', 'أسود', 'اسود',
        'وردي مطفأ', 'وردي', 'مودرن', 'حديث', 'كلاسيكي', 'ناعم',
        'رومانسي', 'بوهيمي', 'مينيمال', 'داكن', 'هادئ', 'فخم',
    ]
    selected_styles = []
    for term in style_terms:
        if term in user_text and term not in selected_styles:
            selected_styles.append(term)
    if selected_styles:
        extracted['style_preference'] = '، '.join(selected_styles[:4])

    city_aliases = {
        'الرياض': ['الرياض', 'رياض'],
        'جدة': ['جدة', 'جده'],
        'مكة': ['مكة', 'مكه'],
        'المدينة المنورة': ['المدينة', 'المدينه'],
        'الدمام': ['الدمام'],
        'الخبر': ['الخبر'],
        'الظهران': ['الظهران'],
        'الطائف': ['الطائف'],
        'القصيم': ['القصيم', 'بريدة', 'بريده', 'عنيزة', 'عنيزه'],
        'أبها': ['أبها', 'ابها'],
        'خميس مشيط': ['خميس مشيط'],
        'تبوك': ['تبوك'],
        'حائل': ['حائل'],
    }
    for city, aliases in city_aliases.items():
        if any(alias in combined_text for alias in aliases):
            extracted['city'] = city
            break

    normalized_digits = user_text.translate(str.maketrans('٠١٢٣٤٥٦٧٨٩', '0123456789'))
    guest_match = re.search(r'(\d{1,4})\s*(?:ضيف|ضيوف|شخص|حضور)', normalized_digits)
    if not guest_match:
        guest_match = re.search(r'(?:عدد|حوالي|قرابة|لـ)\s*(\d{1,4})', normalized_digits)
    if guest_match:
        guest_count = int(guest_match.group(1))
        if 1 <= guest_count <= 5000:
            extracted['guest_count'] = guest_count

    venue_patterns = (
        ('قاعة', ('قاعة', 'قاعه')),
        ('منزل', ('منزل', 'المنزل', 'البيت', 'بيتي')),
        ('استراحة', ('استراحة', 'استراحه')),
        ('فندق', ('فندق', 'فندقية', 'فندقيه')),
        ('مساحة خارجية', ('مساحة خارجية', 'مساحه خارجيه', 'حديقة', 'حديقه', 'خارجي')),
        ('محل أو متجر', ('محل', 'متجر', 'بوتيك', 'معرض تجاري')),
    )
    if any(phrase in user_text for phrase in ('ما حددت المكان', 'المكان مو محدد', 'لسه ما حددنا المكان')):
        extracted['venue'] = 'غير محدد'
    else:
        for venue, keywords in venue_patterns:
            if any(keyword in user_text for keyword in keywords):
                extracted['venue'] = venue
                break

    numeric_date = re.search(
        r'\b(?:20\d{2}[-/]\d{1,2}[-/]\d{1,2}|\d{1,2}[-/]\d{1,2}[-/]20\d{2})\b',
        normalized_digits,
    )
    month_date = re.search(
        r'\b\d{1,2}\s+(?:يناير|فبراير|مارس|ابريل|أبريل|مايو|يونيو|يوليو|اغسطس|أغسطس|سبتمبر|اكتوبر|أكتوبر|نوفمبر|ديسمبر)\b',
        normalized_digits,
    )
    if numeric_date or month_date:
        extracted['event_date'] = (numeric_date or month_date).group(0)

    return extracted


