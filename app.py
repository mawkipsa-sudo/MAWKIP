def check_groq_connection():
    if client is None:
        print('GROQ_API_KEY is not configured. Add it to .env before starting the bot.')
        return

    try:
        response = create_groq_completion(
            [
                {'role': 'system', 'content': SUGGESTION_OUTPUT_INSTRUCTION},
                {
                    'role': 'user',
                    'content': 'اختبار اتصال داخلي: أعد ترحيبًا عربيًا قصيرًا في reply، واجعل suggestions قائمة فارغة.',
                },
            ],
            max_tokens=512,
            timeout=30.0,
        )
        reply = response.choices[0].message.content or ''
        parsed_reply, _ = parse_assistant_output(reply, 'اختبار اتصال')
        if not parsed_reply.strip():
            raise RuntimeError('Groq returned an empty response during startup check.')
        print(f'Groq connected successfully with {ACTIVE_GROQ_MODEL}')
    except Exception as e:
        print('Groq connection failed')
        print(clean_error_message(e))
        traceback.print_exc()

